// Writes sw.js with the full list of shipped files. Run after changing assets or code.
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { posix } from 'node:path';

const walk = dir => readdirSync(dir).flatMap(f => {
  const p = posix.join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const files = ['index.html', 'manifest.webmanifest', ...['src', 'styles', 'vendor', 'assets/ducks', 'assets/guests', 'assets/impostors', 'assets/ui', 'assets/fonts', 'assets/music'].flatMap(walk)];
const hash = createHash('sha1');
for (const f of files) hash.update(readFileSync(f));
const version = hash.digest('hex').slice(0, 10);

writeFileSync('sw.js', `// Generated by tools/make-sw.mjs. Network first so updates show up, cache when offline.
const CACHE = 'bsc-ducks-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 1)};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(fetch(e.request).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match(e.request, { ignoreSearch: true })));
});
`);
console.log(version, files.length);
