// Writes sw.js with the full list of shipped files. Run after changing assets or code.
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { posix } from 'node:path';

const walk = dir => readdirSync(dir).flatMap(f => {
  const p = posix.join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const files = ['index.html', 'manifest.webmanifest', ...['src', 'styles', 'vendor', 'assets/ducks', 'assets/guests', 'assets/impostors', 'assets/ui', 'assets/fonts', 'assets/music'].flatMap(walk)];
const hash = createHash('sha1');
for (const f of files) hash.update(readFileSync(f));
const version = hash.digest('hex').slice(0, 10);

writeFileSync('sw.js', `// Generated by tools/make-sw.mjs. Art and sound come from this version's cache so they
// appear at once; code is network first so updates show up, cache when offline.
const CACHE = 'bsc-ducks-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 1)};
const isMusic = f => f.startsWith('assets/music/');

// The songs are large: fetched one at a time after install, so they never hold up the art.
const cacheMusic = async () => {
  const cache = await caches.open(CACHE);
  for (const f of FILES.filter(isMusic)) await cache.add(f).catch(() => {});
};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.filter(f => !isMusic(f)))).then(() => self.skipWaiting()));
  cacheMusic();
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  const fromNetwork = () => fetch(e.request).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }
    return res;
  });
  if (new URL(e.request.url).pathname.includes('/assets/')) {
    e.respondWith(caches.open(CACHE).then(c => c.match(e.request, { ignoreSearch: true })).then(hit => hit ?? fromNetwork()));
    return;
  }
  e.respondWith(fromNetwork().catch(() => caches.match(e.request, { ignoreSearch: true })));
});
`);
console.log(version, files.length);
